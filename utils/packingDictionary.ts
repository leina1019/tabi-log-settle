/**
 * アイテム名から適切なカテゴリーを推測する
 */
export function suggestCategory(title: string): string | null {
    const normalizedTitle = title.trim();
    if (!normalizedTitle) return null;

    // 完全一致
    if (PACKING_DICTIONARY[normalizedTitle]) {
        return PACKING_DICTIONARY[normalizedTitle];
    }

    // 部分一致
    for (const [key, category] of Object.entries(PACKING_DICTIONARY)) {
        if (normalizedTitle.includes(key) || key.includes(normalizedTitle)) {
            return category;
        }
    }

    return null;
}
